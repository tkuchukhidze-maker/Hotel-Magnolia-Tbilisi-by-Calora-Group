    <p>Tornike Kuchukhidze has been appointed Chief Marketing Officer (CMO) and Head of the Marketing Department of Episode Food Holding and by Calora Group.</p>
    <p>Under his leadership, the group's marketing will bring together five distinct brands: Batumis Sakhlshi, Kutaisis Sakhlshi, Tbilisis Sakhlshi, Hotel Magnolia and Chateau Mere in Kakheti.</p>
    <p>The new marketing vision brings together modern hospitality, the creative industries and technology. The main goal is to build strong, distinctive brands that offer guests not only quality service, but a memorable experience.</p>

    <h2>Marketing as a driver of business growth</h2>
    <p>In Tornike Kuchukhidze's approach, the role of a modern CMO goes beyond traditional marketing. It combines strategic brand management, creative concepts, customer behaviour analysis, digital transformation, team development and commercial growth.</p>
    <p>Within this vision, the group is developing new entertainment formats, themed events, original advertising campaigns, brand partnerships and digital services.</p>
    <p>Special attention goes to projects that create unexpected, engaging and emotional experiences for guests.</p>
    <p>Marketing is no longer only about attracting customers. Every stage of the guest's experience matters: the first contact with the brand, the emotion felt in the space, the return visit and long-term loyalty.</p>

    <h2>Batumis Sakhlshi: a new experience in food and entertainment</h2>
    <p>One of the first examples of this approach is Batumis Sakhlshi, where the traditional restaurant concept is evolving by bringing gastronomy and show business together.</p>
    <p>Georgian music evenings, live performances, Roma shows and themed programmes inspired by Italian and Spanish culture are all part of the brand's entertainment concept.</p>
    <p>The aim is for every evening to have its own story, character and mood, so that guests come to the restaurant not just for dinner, but for a specific experience.</p>
    <p>The concept is supported by creative campaigns, original video projects, new formats of digital communication and modern approaches to guest relations.</p>
    <p>The same strategic principles, adapted to each brand's individual identity, will extend to the group's other venues.</p>
