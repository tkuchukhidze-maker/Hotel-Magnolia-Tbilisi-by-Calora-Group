    <h2>A strong team, creativity and a shared goal</h2>
    <p>The group's marketing is run by a large team whose daily work brings together many professional skills.</p>
    <p>Strategic planning, social media management, visual communication, video production, digital advertising, creative development and campaign delivery are all parts of one system.</p>
    <p>In Tornike Kuchukhidze's view, a strong marketing team is more than a structure that carries out tasks. It is a creative environment where each person can shape the shared result with their own ideas, professionalism and responsibility.</p>
    <p>One of his priorities as a leader is to develop the team's creative potential, strengthen collaboration and build a working culture where creative freedom is tied to concrete business goals.</p>
